export function formatPriceDisplay(price: number, displayPlus?: boolean): string {
  if (price === 0) return '0'
  const withSpaces = Math.round(price).toLocaleString('uk-UA').replace(/\s/g, ' ')
  return displayPlus ? `${withSpaces}+` : withSpaces
}
